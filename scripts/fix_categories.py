async def update_categories():
    factory = get_session_factory()
    async with factory() as session:
        async with session.begin():
            print(f"Начинаю обновление {len(CLEAN_CATEGORIES)} категорий...")
            for cat_id, new_name in CLEAN_CATEGORIES.items():
                await session.execute(
                    update(Category).where(Category.id == cat_id).values(name=new_name)
                )
        print("Все категории успешно обновлены!")

if __name__ == "__main__":
    asyncio.run(update_categories())